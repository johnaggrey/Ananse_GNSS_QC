# Ananse GNSS QC - RINEX Observation File Quality Control
# -------------------------------------------------------
# A tool for performing quality control checks on GNSS
# observation data. Supports RINEX 2.x, 3.x, and 4.x formats.
#
# Quality indicators include:
#   - Observation duration and completeness
#   - Missing observables
#   - Signal/satellite availability
#   - Cycle slip detection
#   - Data gaps
#   - Multipath estimation
#   - SNR quality metrics

